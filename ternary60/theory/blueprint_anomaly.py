def weight_distribution(basis, N):
    """Hamming weight distribution of span(basis) ⊂ F₃^N (bit-sliced enumeration)."""
    from mainq_common import to_bits, badd, bneg
    B = [to_bits(r) for r in basis]
    A = [0] * (N + 1)
    if not B:
        A[0] = 1
        return A
    words = [(0, 0)]
    for b in B[:-1]:
        nb = bneg(b)
        words = [w2 for w in words for w2 in (w, badd(w, b), badd(w, nb))]
    last, nlast = B[-1], bneg(B[-1])
    for w in words:
        for w2 in (w, badd(w, last), badd(w, nlast)):
            A[bin(w2[0] | w2[1]).count("1")] += 1
    return A


def theta_fixed(A, N, tau):
    """Θ_{Λ^h}(τ) = Σ_w A_w ϑ₀^{N−w} ϑ₁^w, ϑ_a = Σ_{y ≡ a (3)} q^{y²/2}."""
    th = [sum(qp(Fr(y * y, 2), tau) for y in range(-60, 61) if y % 3 == a) for a in (0, 1)]
    return sum(Aw * th[0] ** (N - w) * th[1] ** w for w, Aw in enumerate(A) if Aw)


def collapsed_fixed_code(rows, n, h):
    """D = {(x_rep(O))_O : x ∈ C^h}, one representative per h-cycle (h fixed-point-free of order 3)."""
    basis = fixed_code(rows, n, h)
    reps = [c[0] for c, _ in signed_cycles(h)]
    D = [[x[i] for i in reps] for x in basis]
    return (rref(D) if D and any(any(r) for r in D) else []), len(reps)


def find_golay_h(rng):
    C = Code(GOLAY, 12)
    words = set()
    for cs in itertools.product(range(3), repeat=6):
        words.add(tuple(sum(c * r[j] for c, r in zip(cs, GOLAY)) % 3 for j in range(12)))
    tries = 0
    while True:
        tries += 1
        perm = list(range(12)); rng.shuffle(perm)
        p, s = [0] * 12, [1] * 12
        for t in range(4):
            a, b, c = perm[3 * t:3 * t + 3]
            p[a], p[b], p[c] = b, c, a
            s[a], s[b] = rng.choice((1, -1)), rng.choice((1, -1))
            s[c] = s[a] * s[b]
        g = (tuple(p), tuple(s))
        if all(tuple(x % 3 for x in apply(g, r)) in words for r in GOLAY):
            return g, tries, words



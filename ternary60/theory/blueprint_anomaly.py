class Group:
    def __init__(self, els, mul, e):
        self.els, self.mul, self.e = els, mul, e
        self.ne = [x for x in els if x != e]


def cochain_index(G, n):
    return {t: i for i, t in enumerate(itertools.product(G.ne, repeat=n))}


def coboundary_columns(G, n, p):
    """Columns δ(e_t), t ∈ (G∖1)^n, of the normalised coboundary C^n → C^{n+1} with trivial F_p coefficients, as
    dicts row → coefficient."""
    idx_n = cochain_index(G, n)
    idx_n1 = cochain_index(G, n + 1)
    cols = [dict() for _ in idx_n]
    for g, r in idx_n1.items():
        terms = [(g[1:], 1)]
        for i in range(n):
            prod = G.mul(g[i], g[i + 1])
            if prod != G.e:
                terms.append((g[:i] + (prod,) + g[i + 2:], (-1) ** (i + 1)))
        terms.append((g[:n], (-1) ** (n + 1)))
        for t, c in terms:
            j = idx_n[t]
            cols[j][r] = (cols[j].get(r, 0) + c) % p
    return cols, idx_n, idx_n1


def vec(d, p):
    """dict row → coeff (mod p) as an int bitmask (p = 2) or bit-sliced pair (p = 3)."""
    if p == 2:
        v = 0
        for r, c in d.items():
            if c % 2:
                v |= 1 << r
        return v
    a = b = 0
    for r, c in d.items():
        c %= 3
        if c == 1:
            a |= 1 << r
        elif c == 2:
            b |= 1 << r
    return (a, b)


def rank(vs, p):
    if p == 3:
        return bits_rank(list(vs))
    basis = {}
    for v in vs:
        while v:
            low = v & -v
            if low not in basis:
                basis[low] = v
                break
            v ^= basis[low]
    return len(basis)


class Cohomology:
    """Low-degree cohomology H¹, H² of G with trivial F_p coefficients via normalised cochains."""

    def __init__(self, G, p):
        self.G, self.p = G, p
        d1, self.i1, self.i2 = coboundary_columns(G, 1, p)
        d2, _, self.i3 = coboundary_columns(G, 2, p)
        self.B2 = [vec(c, p) for c in d1]                     # coboundaries in C²
        self.r1 = rank(self.B2, p)
        self.r2 = rank((vec(c, p) for c in d2), p)
        self.d2cols = d2
        self.h1 = len(self.i1) - self.r1
        self.h2 = len(self.i2) - self.r2 - self.r1

    def cochain2(self, f):
        """2-cochain from a function f(g, h) → F_p, as a vector in C²."""
        return vec({r: f(*t) % self.p for t, r in self.i2.items()}, self.p)

    def is_cocycle2(self, f):
        # δf = Σ_t f(t) δ(e_t)
        acc = {}
        for t, r in self.i2.items():
            c = f(*t) % self.p
            if c:
                for rr, cc in self.d2cols[r].items():
                    acc[rr] = (acc.get(rr, 0) + c * cc) % self.p
        return not any(acc.values())

    def classes_rank(self, fs):
        """dim of the span of the classes of the 2-cocycles fs in H²."""
        return rank(self.B2 + [self.cochain2(f) for f in fs], self.p) - self.r1



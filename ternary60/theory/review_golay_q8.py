def canonical_gens(S):
    o4 = sorted(g for g in S if mono_mul(g, g) == NEG)
    J = o4[0]
    K = next(g for g in o4 if g not in (J, neg(J)))
    return J, K


def orbit_blocks(J, K):
    """The coordinate orbits of <J, K>, each written (p, Jp, Kp, JKp) with p its smallest element."""
    JK = mono_mul(J, K)
    seen, blocks = set(), []
    for p in range(N):
        if p not in seen:
            b = (p, J[0][p], K[0][p], JK[0][p])
            seen.update(b)
            blocks.append(b)
    return blocks


def inverse(a):
    p, s = a
    q, t = [0] * len(p), [0] * len(p)
    for i in range(len(p)):                   # a e_i = s_i e_{p(i)}  ⇒  a⁻¹ e_{p(i)} = s_i e_i
        q[p[i]], t[p[i]] = i, s[i]
    ai = (tuple(q), tuple(t))
    assert mono_mul(a, ai) == mono_id(len(p)) == mono_mul(ai, a)
    return ai



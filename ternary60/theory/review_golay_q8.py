def centraliser(J, K, S, blocks):
    """All g ∈ Aut(G) commuting with every element of S (a Q₈ with coordinate orbits `blocks`)."""
    Q = list(S)
    base = [b[0] for b in blocks]
    partial = {}
    for i in range(3):
        for j in range(3):
            lst = []
            for q in blocks[j]:
                for eps in (1, -1):
                    pm = {}                                   # h(g e_base) = g h(e_base) = g (eps e_q)
                    for g in Q:
                        x, sx = g[0][base[i]], g[1][base[i]]
                        pm[x] = (g[0][q], sx * eps * g[1][q])
                    assert len(pm) == 4
                    imgs = []
                    for r in GOLAY:
                        a = b = 0
                        for x, (y, s) in pm.items():
                            v = r[x] * s % 3
                            if v == 1:
                                a |= 1 << y
                            elif v == 2:
                                b |= 1 << y
                        imgs.append((a, b))
                    lst.append((pm, imgs))
            partial[(i, j)] = lst
    found, ncand = [], 0
    for pi in itertools.permutations(range(3)):
        L0, L1, L2 = (partial[(i, pi[i])] for i in range(3))
        for c0 in L0:
            for c1 in L1:
                for c2 in L2:
                    ncand += 1
                    if all((c0[1][t][0] | c1[1][t][0] | c2[1][t][0], c0[1][t][1] | c1[1][t][1] | c2[1][t][1]) in WBITS
                           for t in range(len(GOLAY))):
                        p, s = [None] * N, [None] * N
                        for pm in (c0[0], c1[0], c2[0]):
                            for x, (y, sg) in pm.items():
                                p[x], s[x] = y, sg
                        found.append((tuple(p), tuple(s)))
    assert ncand == 3072
    for h in found:
        assert in_aut(h) and all(mono_mul(h, g) == mono_mul(g, h) for g in (J, K))
    return found



def qp(a, tau):
    """q^a = exp(2πi a τ)."""
    return cmath.exp(TWO_PI_I * a * tau)


def eta(tau):
    q = qp(1, tau)
    prod, qn = 1, q
    while abs(qn) > 1e-18:
        prod *= 1 - qn
        qn *= q
    return qp(Fr(1, 24), tau) * prod


def parse_perm(s, n):
    """Digit string without separators → permutation of 0..n−1 (backtracking), as in mainq_orbifold_index."""
    used, out = [False] * n, []
    sys.setrecursionlimit(10000)

    def rec(i):
        if i == len(s):
            return len(out) == n
        for L in (1, 2, 3):
            if i + L <= len(s) and (L == 1 or s[i] != "0"):
                v = int(s[i:i + L])
                if v < n and not used[v]:
                    used[v] = True; out.append(v)
                    if rec(i + L):
                        return True
                    used[v] = False; out.pop()
        return False
    return tuple(out) if rec(0) else None


class Code:
    """A linear code with a reduced echelon basis (pivots = 1) for fast membership tests."""

    def __init__(self, rows, n):
        self.n = n
        self.R = rref(rows)
        self.piv = [next(j for j in range(n) if r[j]) for r in self.R]

    def contains(self, v):
        v = [x % 3 for x in v]
        for r, p in zip(self.R, self.piv):
            c = v[p]
            if c:
                v = [(x - c * y) % 3 for x, y in zip(v, r)]
        return not any(v)

    def is_aut(self, g):
        return all(self.contains(apply(g, r)) for r in self.R)

    def random_word(self, rng):
        v = [0] * self.n
        for r in self.R:
            c = rng.randrange(3)
            if c:
                v = [(x + c * y) % 3 for x, y in zip(v, r)]
        return v


def apply(g, v):
    """(g v)_{p(i)} = s_i v_i (works for integer vectors and F₃ vectors alike)."""
    p, s = g
    y = [0] * len(p)
    for i, x in enumerate(v):
        y[p[i]] = s[i] * x
    return y


def order(g):
    e, x, k = mono_id(len(g[0])), g, 1
    while x != e:
        x, k = mono_mul(g, x), k + 1
    return k


def signed_cycles(g):
    p, s = g
    seen, out = set(), []
    for i in range(len(p)):
        if i not in seen:
            c, j, sg = [], i, 1
            while j not in seen:
                seen.add(j); c.append(j); sg *= s[j]; j = p[j]
            out.append((c, sg))
    return out


def rho(g):
    """(fixed-point-free on ℝⁿ?, ρ_g = ¼ Σ θ(1−θ) over the eigenvalues e^{2πiθ}, θ ∈ [0,1)). A signed cycle of length
    L with sign product s has eigenvalues θ = (j + [s = −1]/2)/L. ρ_g = (1/24) Σ d_k (k − 1/k) for Frame shape Π k^{d_k}."""
    fpf, r = True, Fr(0)
    for c, sg in signed_cycles(g):
        L = len(c)
        for j in range(L):
            th = (Fr(j) + (Fr(1, 2) if sg == -1 else 0)) / L
            fpf &= th != 0
            r += th * (1 - th) / 4
    return fpf, r


def n_minus(g):
    return sum(1 for x in g[1] if x == -1)



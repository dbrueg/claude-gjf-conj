def free_q8(Jn, Kn, n):
    G = closure([Jn, Kn], n)
    orbs = set()
    for x in range(n):
        orbs.add(frozenset(g[0][x] for g in G))
    return len(G) == 8 and all(len(o) == 4 for o in orbs) and all(
        set(cycle_type(g[0])) == {2} for g in (Jn, Kn, mono_mul(Jn, Kn)))


def selfdual(rows, n):
    return len(rows) == n // 2 and all(dot(a, c) == 0 for a in rows for c in rows)



def R_by_weight(blocks):
    """Contributions to R_σ(G) (σ covering all 12 coordinates) by codeword weight."""
    out = Counter()
    for c in W:
        p = 1
        for b in blocks:
            p *= LAM[sum(1 for j in b if c[j])]
            if not p:
                break
        if p:
            out[wt(c)] += p
    return dict(sorted(out.items()))


HEXADS = sorted({supp(w) for w in W if wt(w) == 6})


def H_count(blocks):
    """#(hexad X, block B) with X ⊇ B and |X ∩ B'| = 1 for the two other blocks B'."""
    bm = [sum(1 << x for x in b) for b in blocks]
    h = 0
    for X in HEXADS:
        for i, B in enumerate(bm):
            if X & B == B and all(bin(X & B2).count("1") == 1 for j, B2 in enumerate(bm) if j != i):
                h += 1
    return h


def type2_systems(J, K, blocks):
    """Q₈-stable full 3-block systems of type (ii): yields (i, tname, matching, σ)."""
    JK = mono_mul(J, K)
    for i in range(3):
        j, k = [x for x in range(3) if x != i]
        for tname, t in (("J", J), ("K", K), ("JK", JK)):
            def tpairs(B):
                out = []
                for x in B:
                    if not any(x in pr for pr in out):
                        out.append((x, t[0][x]))
                return out
            Pj, Pk = tpairs(blocks[j]), tpairs(blocks[k])
            for sw in (0, 1):
                yield i, tname, sw, [blocks[i], Pj[0] + Pk[sw], Pj[1] + Pk[1 - sw]]


